// Package storage persists reading progress for PDF files and app settings
// in a local SQLite database (pure-Go driver, no CGO).
package storage

// FileRec is one row of the files table: everything we know about a PDF
// on disk. UpdatedAt is RFC3339 formatted and refreshed by every setter
// that mutates the record.
type FileRec struct {
	Path, Status     string // status ∈ todo|reading|done|skip
	Page, TotalPages int
	Starred          bool
	UpdatedAt        string // RFC3339
}

// validStatuses is the closed set accepted by SetStatus.
var validStatuses = map[string]bool{
	"todo":    true,
	"reading": true,
	"done":    true,
	"skip":    true,
}

// Note is one row of the notes table: a hand-written note for one PDF,
// optionally pinned to a page (Page nil = the note is document-level).
// TS is RFC3339, generated by AddNote. AnnIDs holds the ids of the
// annotations linked to this note (empty when unlinked); only ListNotes
// fills it — AddNote returns an empty slice.
type Note struct {
	ID, FilePath, Text string
	Page               *int
	TS                 string // RFC3339
	AnnIDs             []string
}

// Annotation is one row of the annotations table: a highlight, line or
// box drawn on a PDF page. Data is the normalised geometry JSON and is
// stored verbatim — the storage layer never parses or validates it.
// CreatedAt is RFC3339, generated by AddAnnotation.
type Annotation struct {
	ID, FilePath          string
	Page                  int
	Kind, Data, CreatedAt string // kind ∈ highlight|line|box
}

// validAnnKinds is the closed set accepted by AddAnnotation.
var validAnnKinds = map[string]bool{
	"highlight": true,
	"line":      true,
	"box":       true,
}
